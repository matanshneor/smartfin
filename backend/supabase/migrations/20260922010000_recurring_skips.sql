/* תאריכים שדולגו בכוונה בסדרה קבועה.
 *
 * מנוע העסקאות הקבועות משלים חודשים חסרים, והוא מחליט מה חסר לפי מה
 * שקיים. אין לו דרך להבחין בין "עוד לא יצרתי את זה" לבין "זה נמחק
 * בכוונה" — בשני המקרים הוא רואה חור ומשלים אותו.
 *
 * התוצאה: מחיקת מופע בודד בוטלה מעצמה בריצה הבאה. מי שביטל את Netflix
 * לחודש אחד מחק את ספטמבר, ולמחרת הוא חזר. עד היום זה לא צץ כי לא
 * הייתה דרך למחוק מופע בודד במכוון; מרגע שהדיאלוג מציע "רק את זו",
 * זה הופך לתכונה שלא עובדת.
 *
 * מערך על שורת התבנית ולא טבלה נפרדת: הנתון שייך לסדרה, תמיד נקרא
 * יחד איתה, ולעולם לא נשאל בפני עצמו. טבלה הייתה מוסיפה join לכל
 * ריצה של המנוע בלי להוסיף שום יכולת.
 */
alter table public.transactions
  add column if not exists recurring_skips date[];

comment on column public.transactions.recurring_skips is
  'תאריכי מופעים שהמשתמש מחק במכוון; המנוע לא ייצור אותם מחדש';
